def _schema_id_url(relative_path: str) -> str:
    return f"{SCHEMA_BASE_URL}/{relative_path}"


def build_profile_h_common() -> dict[str, Any]:
    return {
        "$schema": SCHEMA_DRAFT,
        "$id": _schema_id_url("profile-h/1.0/common.schema.json"),
        "title": "MCP++ Profile H 1.0 common definitions",
        "$defs": {
            "cid": dict(_CID),
            "did": dict(_DID),
            "timestamp": dict(_TIME),
            "amount": dict(_AMOUNT),
            "network": dict(_NETWORK),
            "signature": dict(_SIG),
            "requirement": json.loads(json.dumps(_REQUIREMENT)),
        },
    }


def build_profile_h_artifacts() -> dict[str, Any]:
    defs: dict[str, Any] = {
        "cid": dict(_CID),
        "did": dict(_DID),
        "time": dict(_TIME),
        "amount": dict(_AMOUNT),
        "network": dict(_NETWORK),
        "sig": dict(_SIG),
        "common": {
            "type": "object",
            "required": list(COMMON_FIELDS),
            "properties": {
                "schema": {"type": "string"},
                "createdAt": {"$ref": "#/$defs/time"},
                "parents": {
                    "type": "array",
                    "maxItems": 256,
                    "uniqueItems": True,
                    "items": {"$ref": "#/$defs/cid"},
                },
                "correlationId": {
                    "type": "string",
                    "minLength": 1,
                    "maxLength": 128,
                },
            },
        },
        "requirement": json.loads(json.dumps(_REQUIREMENT)),
    }

    for artifact in PROFILE_H_ARTIFACTS:
        required = list(COMMON_FIELDS) + list(artifact.fields)
        properties: dict[str, Any] = {
            "schema": {"const": artifact.schema_marker},
            "createdAt": {"$ref": "#/$defs/time"},
            "parents": {"type": "array", "items": {"$ref": "#/$defs/cid"}},
            "correlationId": {"type": "string"},
        }
        for name in artifact.fields:
            if name in artifact.property_schema:
                properties[name] = dict(artifact.property_schema[name])
            else:
                properties[name] = _prop_for_field(
                    name,
                    enums=artifact.enums,
                    nullable=artifact.nullable_fields,
                    consts=artifact.const_fields,
                    time_alias="time",
                )
        defs[artifact.kind] = {
            "allOf": [
                {"$ref": "#/$defs/common"},
                {
                    "type": "object",
                    "additionalProperties": False,
                    "required": required,
                    "properties": properties,
                },
            ]
        }

    return {
        "$schema": SCHEMA_DRAFT,
        "$id": _schema_id_url("profile-h/1.0/artifacts.schema.json"),
        "title": "MCP++ Profile H 1.0 canonical artifacts",
        "description": (
            "Closed DAG-JSON shapes. Semantic, CID codec, expiry, redaction, "
            "and negotiated-bound checks are additionally enforced by the "
            "Profile H codecs."
        ),
        "oneOf": [{"$ref": f"#/$defs/{a.kind}"} for a in PROFILE_H_ARTIFACTS],
        "$defs": defs,
    }


