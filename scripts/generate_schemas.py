def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Generate MCP++ JSON Schemas from the canonical SchemaId@1 source "
            "and check language-model drift."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Verify on-disk schemas and language models agree with the "
            "canonical source; exit 1 on drift."
        ),
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="Print the SchemaId@1 catalog and exit.",
    )
    parser.add_argument(
        "--fingerprint",
        action="store_true",
        help="Print the SHA-256 fingerprint of the canonical IR and exit.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="With generate mode, list files that would be written.",
    )
    parser.add_argument(
        "--schemas-root",
        type=Path,
        default=None,
        help="Override schemas directory (default: package schemas/).",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=None,
        help="Override repository root for language-model paths.",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)

    schemas_root = (args.schemas_root or SCHEMAS_ROOT).resolve()
    repo_root = (args.repo_root or _repo_root()).resolve()

    if args.list:
        for entry in SCHEMA_CATALOG:
            managed = "managed" if entry.managed else "frozen"
            iface = entry.interface or "-"
            print(
                f"{entry.schema_id}\t{entry.relative_path}\t{iface}\t{managed}"
            )
        print(f"fingerprint\t{canonical_fingerprint()}", file=sys.stderr)
        return 0

    if args.fingerprint:
        print(canonical_fingerprint())
        return 0

    if args.check:
        try:
            run_check(repo_root, schemas_root)
        except DriftError as exc:
            print("SCHEMA DRIFT DETECTED (SchemaId@1)", file=sys.stderr)
            for line in exc.findings:
                print(f"  - {line}", file=sys.stderr)
            print(
                "\nCanonical source: "
                "ipfs_accelerate_py/mcplusplus/scripts/generate_schemas.py",
                file=sys.stderr,
            )
            print(
                "Fix: align language models with the IR, or re-run without "
                "--check to regenerate managed JSON Schema files.",
                file=sys.stderr,
            )
            return 1
        print(
            f"OK: schemas and language models agree with canonical source "
            f"(fingerprint {canonical_fingerprint()[:16]}…)"
        )
        return 0

    # Default: generate managed schemas from the canonical source.
    written = write_schemas(schemas_root, dry_run=args.dry_run)
    action = "would write" if args.dry_run else "wrote"
    for relative in written:
        print(f"{action}: {schemas_root / relative}")
    print(f"{action} {len(written)} managed schema file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
