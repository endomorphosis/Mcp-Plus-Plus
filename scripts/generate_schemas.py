@dataclass(frozen=True)
class ArtifactKind:
    """One closed Profile H artifact kind in the canonical IR."""

    kind: str
    slug: str
    fields: tuple[str, ...]
    # Optional property overrides (defaults derived from field name heuristics).
    property_schema: Mapping[str, Any] = field(default_factory=dict)
    enums: Mapping[str, Sequence[str]] = field(default_factory=dict)
    nullable_fields: frozenset[str] = field(default_factory=frozenset)
    const_fields: Mapping[str, Any] = field(default_factory=dict)

    @property
    def schema_marker(self) -> str:
        return f"{PROFILE_H_MARKER_PREFIX}/{self.slug}@{PROFILE_H_VERSION}"


def _prop_for_field(
    name: str,
    *,
    enums: Mapping[str, Sequence[str]],
    nullable: frozenset[str],
    consts: Mapping[str, Any],
    time_alias: str = "time",
) -> dict[str, Any]:
    if name in consts:
        return {"const": consts[name]}
    if name == "schema":
        raise AssertionError("schema marker handled separately")
    if name in enums:
        schema: dict[str, Any] = {"enum": list(enums[name])}
    elif name.endswith("Cid") or name.endswith("Commitment"):
        schema = {"$ref": f"#/$defs/cid"}
    elif name.endswith("Did") or name in {"serverDid", "sellerDid", "verifierDid"}:
        schema = {"$ref": "#/$defs/did"}
    elif name in {
        "createdAt",
        "validFrom",
        "expiresAt",
        "verifiedAt",
        "settledAt",
        "recordedAt",
        "requestedAt",
        "decidedAt",
        "quotaUnits",
        "consumedUnits",
    }:
        schema = {"$ref": f"#/$defs/{time_alias}"}
    elif name == "amount":
        schema = {"$ref": "#/$defs/amount"}
    elif name == "network":
        schema = {"$ref": "#/$defs/network"}
    elif name == "signature":
        schema = {"$ref": "#/$defs/sig"}
    elif name == "signatureAlg":
        schema = {"const": "Ed25519"}
    elif name == "requirements":
        schema = {
            "type": "array",
            "minItems": 1,
            "maxItems": 32,
            "items": {"$ref": "#/$defs/requirement"},
        }
    elif name == "requirementIndex":
        schema = {"type": "integer", "minimum": 0, "maximum": 31}
    elif name == "units":
        schema = {"type": "integer", "minimum": 1, "maximum": 9007199254740991}
    elif name == "httpMethod":
        schema = {
            "type": ["string", "null"],
            "enum": ["GET", "POST", "PUT", "PATCH", "DELETE", None],
        }
    elif name == "httpRoute":
        schema = {"type": ["string", "null"], "maxLength": 512}
    elif name in {
        "operationName",
        "ability",
        "catalogVersion",
        "scheme",
        "asset",
        "payee",
        "nonce",
        "idempotencyKey",
        "reasonCode",
        "unit",
        "correlationId",
    }:
        max_len = {
            "operationName": 256,
            "ability": 256,
            "asset": 256,
            "payee": 256,
            "catalogVersion": 64,
            "scheme": 64,
            "unit": 128,
            "nonce": 128,
            "idempotencyKey": 128,
            "reasonCode": 128,
            "correlationId": 128,
        }.get(name, 256)
        schema = {"type": "string", "minLength": 1, "maxLength": max_len}
    else:
        schema = {"type": "string"}

    if name in nullable and "type" not in schema:
        schema = {"anyOf": [schema, {"type": "null"}]}
    elif name in nullable and schema.get("type") not in (["string", "null"],):
        if "$ref" in schema or "enum" in schema or "const" in schema:
            schema = {"anyOf": [schema, {"type": "null"}]}
    return schema


