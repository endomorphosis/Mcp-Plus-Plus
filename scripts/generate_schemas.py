class DriftError(Exception):
    """One or more schema drift findings."""

    def __init__(self, findings: Sequence[str]) -> None:
        self.findings = list(findings)
        super().__init__("\n".join(self.findings))


def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def extract_artifact_ir_from_schema(document: Mapping[str, Any]) -> dict[str, dict[str, Any]]:
    """Extract kind → {marker, fields} from a Profile H artifacts schema."""
    defs = document.get("$defs")
    if not isinstance(defs, Mapping):
        raise ValueError("artifacts schema missing $defs")
    out: dict[str, dict[str, Any]] = {}
    for kind, body in defs.items():
        if not isinstance(kind, str) or not kind[:1].isupper():
            continue
        if not isinstance(body, Mapping):
            continue
        marker = None
        required: list[str] = []
        for part in body.get("allOf") or ():
            if not isinstance(part, Mapping):
                continue
            props = part.get("properties") or {}
            if "schema" in props and isinstance(props["schema"], Mapping):
                marker = props["schema"].get("const")
            if "required" in part and isinstance(part["required"], list):
                required = [str(x) for x in part["required"]]
        if marker is None:
            continue
        specific = [f for f in required if f not in COMMON_FIELDS]
        out[kind] = {"marker": marker, "fields": specific}
    return out


def _parse_python_string_dict(source: str, name: str) -> dict[str, str]:
    """Parse ``NAME = { "K": "v", ... }`` assignments from Python source."""
    pattern = rf"^{name}\s*=\s*\{{(.*?)^\}}"
    match = re.search(pattern, source, flags=re.MULTILINE | re.DOTALL)
    if not match:
        raise ValueError(f"could not find {name} dict in Python source")
    # Reconstruct a literal and evaluate safely via json after quote normalize.
    body = "{" + match.group(1) + "}"
    # Allow trailing commas by using ast.literal_eval.
    import ast

    value = ast.literal_eval(body)
    if not isinstance(value, dict):
        raise ValueError(f"{name} is not a dict")
    return {str(k): str(v) for k, v in value.items()}


def extract_python_profile_h(path: Path) -> tuple[dict[str, str], dict[str, list[str]]]:
    text = path.read_text(encoding="utf-8")
    schemas = _parse_python_string_dict(text, "SCHEMAS")
    # FIELDS values may be space-separated strings before the split rewrite.
    pattern = r"^FIELDS\s*=\s*\{(.*?)^\}"
    match = re.search(pattern, text, flags=re.MULTILINE | re.DOTALL)
    if not match:
        raise ValueError("could not find FIELDS dict in Python Profile H codec")
    import ast

    raw = ast.literal_eval("{" + match.group(1) + "}")
    fields: dict[str, list[str]] = {}
    for key, value in raw.items():
        if isinstance(value, str):
            fields[str(key)] = value.split()
        elif isinstance(value, (list, tuple)):
            fields[str(key)] = [str(x) for x in value]
        else:
            raise ValueError(f"unexpected FIELDS value type for {key}")
    return schemas, fields


def extract_typescript_profile_h(path: Path) -> tuple[dict[str, str], dict[str, list[str]]]:
    text = path.read_text(encoding="utf-8")
    schemas: dict[str, str] = {}
    for kind, slug in re.findall(
        r"([A-Za-z][A-Za-z0-9]*)\s*:\s*'([a-z0-9-]+)'",
        _slice_ts_object(text, "SCHEMAS"),
    ):
        schemas[kind] = slug

    fields_body = _slice_ts_object(text, "FIELDS")
    fields: dict[str, list[str]] = {}
    # Entries look like: Kind:'a b c'.split(' ')  or Kind: 'a b c'.split(" ")
    for kind, field_str in re.findall(
        r"([A-Za-z][A-Za-z0-9]*)\s*:\s*'([^']+)'\s*\.split\s*\(\s*['\"] ['\"]\s*\)",
        fields_body,
    ):
        fields[kind] = field_str.split()
    if not fields:
        # Alternate: Kind:['a','b'] form
        for kind, arr in re.findall(
            r"([A-Za-z][A-Za-z0-9]*)\s*:\s*\[([^\]]+)\]",
            fields_body,
        ):
            fields[kind] = re.findall(r"['\"]([A-Za-z0-9]+)['\"]", arr)
    return schemas, fields


def _slice_ts_object(source: str, name: str) -> str:
    # Match `const NAME:...={...}` or `const NAME={...}`
    match = re.search(
        rf"(?:const|let|var)\s+{name}\s*(?::[^=]+)?=\s*\{{",
        source,
    )
    if not match:
        raise ValueError(f"could not find TypeScript object {name}")
    start = match.end() - 1
    depth = 0
    for idx in range(start, len(source)):
        ch = source[idx]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return source[start + 1 : idx]
    raise ValueError(f"unbalanced braces for TypeScript object {name}")


def extract_go_profile_h_markers(path: Path) -> dict[str, str] | None:
    """Optional Go markers; returns None when Profile H is not yet modeled."""
    if not path.is_file():
        return None
    text = path.read_text(encoding="utf-8")
    if "profile-h" not in text and "PaidCapability" not in text:
        return None
    found = dict(
        re.findall(
            r'"(Paid\w+|Payment\w+|Settlement\w+|Usage\w+|Refund\w+|Access\w+)"\s*:\s*"([^"]+)"',
            text,
        )
    )
    return found or None


def extract_rust_profile_h_markers(path: Path) -> dict[str, str] | None:
    if not path.is_file():
        return None
    text = path.read_text(encoding="utf-8")
    if "profile-h" not in text and "PaidCapability" not in text:
        return None
    found = dict(
        re.findall(
            r'"(Paid\w+|Payment\w+|Settlement\w+|Usage\w+|Refund\w+|Access\w+)"\s*=>\s*"([^"]+)"',
            text,
        )
    )
    return found or None


