def check_catalog_files(schemas_root: Path) -> list[str]:
    findings: list[str] = []
    for entry in SCHEMA_CATALOG:
        path = schemas_root / entry.relative_path
        if not path.is_file():
            findings.append(
                f"catalog: missing schema file for {entry.schema_id}: "
                f"{entry.relative_path}"
            )
            continue
        try:
            doc = _load_json(path)
        except json.JSONDecodeError as exc:
            findings.append(f"catalog: invalid JSON at {entry.relative_path}: {exc}")
            continue
        if not isinstance(doc, dict):
            findings.append(f"catalog: {entry.relative_path} root must be an object")
            continue
        expected_id = _schema_id_url(entry.relative_path)
        actual_id = doc.get("$id")
        if actual_id != expected_id:
            findings.append(
                f"catalog: {entry.relative_path} $id drift: "
                f"expected {expected_id!r}, got {actual_id!r}"
            )
        if entry.family == "canonicalization":
            algo = (
                (doc.get("$defs") or {}).get("algorithmId") or {}
            )
            if isinstance(algo, dict) and algo.get("const") != "mcpp-jcs-v1":
                findings.append(
                    f"catalog: {entry.relative_path} algorithmId const must be "
                    f"mcpp-jcs-v1 (McppJcsV1@1)"
                )
    return findings


def check_managed_generation(schemas_root: Path) -> list[str]:
    """Compare managed on-disk documents to builders (structural Profile H IR).

    Full pretty-print equality is not required for pre-existing compact
    documents; the closed kind/marker/field IR must match exactly.  For
    common and x402, deep equality of the JSON value is required after load.
    """
    findings: list[str] = []
    expected_artifacts = build_profile_h_artifacts()
    expected_ir = extract_artifact_ir_from_schema(expected_artifacts)

    artifacts_path = schemas_root / "profile-h/1.0/artifacts.schema.json"
    if artifacts_path.is_file():
        disk_doc = _load_json(artifacts_path)
        try:
            disk_ir = extract_artifact_ir_from_schema(disk_doc)
        except ValueError as exc:
            findings.append(f"disk artifacts schema: {exc}")
            disk_ir = {}
        if set(disk_ir) != set(expected_ir):
            findings.append(
                "disk artifacts schema kinds disagree with canonical source: "
                f"disk={sorted(disk_ir)} canonical={sorted(expected_ir)}"
            )
        for kind in sorted(set(expected_ir) & set(disk_ir)):
            if disk_ir[kind]["marker"] != expected_ir[kind]["marker"]:
                findings.append(
                    f"disk artifacts schema marker drift for {kind}: "
                    f"disk={disk_ir[kind]['marker']!r} "
                    f"canonical={expected_ir[kind]['marker']!r}"
                )
            if disk_ir[kind]["fields"] != expected_ir[kind]["fields"]:
                findings.append(
                    f"disk artifacts schema field drift for {kind}: "
                    f"disk={disk_ir[kind]['fields']} "
                    f"canonical={expected_ir[kind]['fields']}"
                )
        # oneOf coverage
        one_of = disk_doc.get("oneOf") or []
        refs = {
            item.get("$ref", "").rsplit("/", 1)[-1]
            for item in one_of
            if isinstance(item, Mapping)
        }
        expected_kinds = {a.kind for a in PROFILE_H_ARTIFACTS}
        if refs != expected_kinds:
            findings.append(
                f"disk artifacts schema oneOf drift: disk={sorted(refs)} "
                f"canonical={sorted(expected_kinds)}"
            )
    else:
        findings.append("disk: missing profile-h/1.0/artifacts.schema.json")

    # common + x402: deep equality after JSON round-trip (formatting-insensitive)
    for relative, builder in (
        ("profile-h/1.0/common.schema.json", build_profile_h_common),
        ("profile-h/1.0/x402-v2.schema.json", build_profile_h_x402_v2),
    ):
        path = schemas_root / relative
        if not path.is_file():
            findings.append(f"disk: missing {relative}")
            continue
        disk_doc = _load_json(path)
        expected = builder()
        if disk_doc != expected:
            # Allow equivalent documents that only differ in non-semantic key
            # order by comparing canonical dumps.
            if _canonical_json(disk_doc) != _canonical_json(expected):
                findings.append(
                    f"disk schema disagrees with canonical source: {relative}"
                )
    return findings


def _canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def check_language_models(repo_root: Path) -> list[str]:
    findings: list[str] = []
    expected_schemas = profile_h_schemas_map()
    expected_fields = profile_h_fields_map()
    expected_markers = profile_h_markers_map()

    for model in LANGUAGE_MODELS:
        path = repo_root / model.relative_path
        if not path.is_file():
            if model.required:
                findings.append(
                    f"language model missing ({model.language}): "
                    f"{model.relative_path}"
                )
            continue

        try:
            if model.language == "python":
                schemas, fields = extract_python_profile_h(path)
            elif model.language == "typescript":
                schemas, fields = extract_typescript_profile_h(path)
            elif model.language == "go":
                markers = extract_go_profile_h_markers(path)
                if markers is None:
                    continue  # not yet modeled — not a drift failure
                schemas = markers
                fields = {}
            elif model.language == "rust":
                markers = extract_rust_profile_h_markers(path)
                if markers is None:
                    continue
                schemas = markers
                fields = {}
            else:
                findings.append(f"unknown language model: {model.language}")
                continue
        except ValueError as exc:
            findings.append(
                f"language model parse failed ({model.language} "
                f"{model.relative_path}): {exc}"
            )
            continue

        if schemas != expected_schemas and model.language in {"python", "typescript"}:
            # SCHEMAS maps kind → slug
            if set(schemas) != set(expected_schemas):
                findings.append(
                    f"language model {model.language} kind set disagrees with "
                    f"canonical source: model={sorted(schemas)} "
                    f"canonical={sorted(expected_schemas)}"
                )
            for kind in sorted(set(schemas) & set(expected_schemas)):
                if schemas[kind] != expected_schemas[kind]:
                    findings.append(
                        f"language model {model.language} slug drift for {kind}: "
                        f"model={schemas[kind]!r} "
                        f"canonical={expected_schemas[kind]!r}"
                    )
        elif schemas and model.language in {"go", "rust"}:
            # May store full markers or slugs.
            for kind, value in schemas.items():
                if kind not in expected_markers:
                    findings.append(
                        f"language model {model.language} unknown kind {kind}"
                    )
                    continue
                if value not in {expected_schemas.get(kind), expected_markers[kind]}:
                    findings.append(
                        f"language model {model.language} marker/slug drift for "
                        f"{kind}: model={value!r}"
                    )

        if fields:
            if set(fields) != set(expected_fields):
                findings.append(
                    f"language model {model.language} field-kind set disagrees: "
                    f"model={sorted(fields)} canonical={sorted(expected_fields)}"
                )
            for kind in sorted(set(fields) & set(expected_fields)):
                if fields[kind] != expected_fields[kind]:
                    findings.append(
                        f"language model {model.language} field drift for {kind}: "
                        f"model={fields[kind]} canonical={expected_fields[kind]}"
                    )

        # Marker string presence check for required models.
        if model.language in {"python", "typescript"}:
            text = path.read_text(encoding="utf-8")
            for kind, marker in expected_markers.items():
                # Codecs compose markers as f"mcp++/profile-h/{slug}@1.0"
                slug = expected_schemas[kind]
                if slug not in text and marker not in text:
                    findings.append(
                        f"language model {model.language} missing schema slug "
                        f"for {kind}: {slug}"
                    )

    return findings


def run_check(repo_root: Path, schemas_root: Path) -> None:
    findings: list[str] = []
    findings.extend(check_catalog_files(schemas_root))
    findings.extend(check_managed_generation(schemas_root))
    findings.extend(check_language_models(repo_root))
    if findings:
        raise DriftError(findings)


