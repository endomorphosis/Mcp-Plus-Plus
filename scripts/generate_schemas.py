def iter_managed_outputs() -> Iterable[tuple[str, dict[str, Any]]]:
    for relative, builder in BUILDERS.items():
        yield relative, builder()


def write_schemas(schemas_root: Path, *, dry_run: bool = False) -> list[str]:
    written: list[str] = []
    for relative, document in iter_managed_outputs():
        path = schemas_root / relative
        text = render_json(document)
        if dry_run:
            written.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(relative)
    return written


