def render_json(document: Mapping[str, Any]) -> str:
    """Stable UTF-8 JSON with trailing newline (generated-file convention)."""
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def canonical_fingerprint() -> str:
    """SHA-256 of the closed Profile H IR + catalog ids (not pretty-print)."""
    payload = {
        "interface": "SchemaId@1",
        "catalog": [
            {
                "schema_id": e.schema_id,
                "relative_path": e.relative_path,
                "family": e.family,
                "managed": e.managed,
                "interface": e.interface,
            }
            for e in SCHEMA_CATALOG
        ],
        "profile_h": {
            "version": PROFILE_H_VERSION,
            "common_fields": list(COMMON_FIELDS),
            "artifacts": [
                {
                    "kind": a.kind,
                    "slug": a.slug,
                    "marker": a.schema_marker,
                    "fields": list(a.fields),
                    "enums": {k: list(v) for k, v in a.enums.items()},
                    "nullable": sorted(a.nullable_fields),
                }
                for a in PROFILE_H_ARTIFACTS
            ],
        },
    }
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


